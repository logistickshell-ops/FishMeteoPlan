export function isSpawningRestrictionActive(date = new Date()): boolean {
  const month = date.getMonth() + 1;
  const day = date.getDate();
  return (month === 4 && day >= 15) || month === 5 || (month === 6 && day <= 1);
}

export function getActiveSpawningRestrictions(date = new Date()): string[] {
  return isSpawningRestrictionActive(date) ? spawningRules.restrictions : [];
}
