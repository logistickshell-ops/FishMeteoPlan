export interface LocationInfo {
  id: string;
  name: string;
  nameGenitive: string; // "в Ярославле", "на Рыбинском водохранилище"
  coords: { lat: number; lon: number };
  description: string;
  type: "river" | "lake" | "reservoir";
  avgDepth: string;
}

export interface FishSpecies {
  id: string;
  name: string;
  icon: string;
  type: "peaceful" | "predator";
  bait: string[];
  seasonalBait: {
    spring: string[];
    summer: string[];
    autumn: string[];
    winter: string[];
  };
  temp: [number, number]; // Optimal min/max water temperature
  pressure: [number, number]; // Optimal pressure (mmHg)
  pressureSensitivity: number; // 0-1, how sensitive to pressure drops
  wind: number; // Max tolerated wind speed (m/s)
  windPreference: "windward" | "leeward" | "any"; // Where they prefer to be
  active: ("morning" | "day" | "evening" | "night")[];
  visibility: "any" | "low" | "high"; // Light preference
  habitats: string[];
  oxygenNeed: "low" | "medium" | "high";
  legalSize: string;
  dailyLimit: string;
  description: string;
  tackle: string[];
  behaviorNotes: string;
}

