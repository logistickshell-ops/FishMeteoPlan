// Magnetic storm index simulation (based on solar activity patterns)
export function getMagneticStormIndex(date: Date): number {
  // Simplified model: based on day-of-year and known solar cycle patterns
  const dayOfYear = Math.floor((date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24));
  // Simulate periodic peaks (roughly every 27 days - solar rotation)
  const solarRotation = 27;
  const cyclePosition = (dayOfYear % solarRotation) / solarRotation;
  // Peak around position 0.3-0.5 and 0.8-0.9
  const base = Math.sin(cyclePosition * Math.PI * 2) * 0.3 + 0.3;
  // Add some randomness seeded by day
  const pseudoRandom = ((dayOfYear * 9301 + 49297) % 233280) / 233280;
  return Math.max(0, Math.min(1, base + (pseudoRandom - 0.5) * 0.4));
}

// Season helper
export function getSeason(month: number): "spring" | "summer" | "autumn" | "winter" {
  if (month >= 3 && month <= 5) return "spring";
  if (month >= 6 && month <= 8) return "summer";
  if (month >= 9 && month <= 11) return "autumn";
  return "winter";
}

